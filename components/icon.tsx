export const ICON_NAMES = Object.keys(ICONS);

export function Icon({
  name,
  className,
}: {
  name?: string | null;
  className?: string;
}) {
  const Cmp = (name && ICONS[name]) || Stethoscope;
  return <Cmp className={className} aria-hidden="true" />;
}
